from google import genai
import config

print("[DEBUG] Налаштування клієнта Gemini...")
ai_client = genai.Client(api_key=config.GEMINI_API_KEY)

def generate_news_digest(tg_content: str) -> str:
    prompt = f"""
    Твоє завдання - структурувати сирі новини у лаконічний дайджест.

    Ось дані:
    {tg_content}
    
    === ПРАВИЛА ФІЛЬТРАЦІЇ ===
    Ігноруй: кримінал, ДТП, збори коштів, рекламу, будь-який контент про рф, погоду, побутові скарги (ями, смітники) та дрібні локальні події. 
    Якщо новини не відповідають критеріям якості - НЕ пиши нічого зайвого, просто поверни рядок: "На сьогодні важливих новин немає."

    === СУВОРІ ПРАВИЛА ОФОРМЛЕННЯ ===
    1. Жодних привітань ("Доброго ранку"), жодних епілогів ("Бажаємо гарного дня"), жодних пояснень, чому новин немає.
    2. Якщо новини є: просто перелічи їх з емодзі. 
    3. Жодного markdown (без зірочок **, без лапок `). Тільки чистий текст.
    4. Заголовки секцій: === [ЕМОДЗІ] НАЗВА ===
    5. Посилання: (Джерело: посилання)
    6. Ніяких довгих тире. Тільки короткі або пробіли.
    7. Тон: суто інформаційний, без оціночних судджень.
    """

    response = ai_client.models.generate_content(
        model='gemini-3.5-flash',
        contents=prompt,
    )

    if response.usage_metadata:
        total_tokens = response.usage_metadata.total_token_count
        print(f"[AI DEBUG] Генерація успішна. Всього використано токенів: {total_tokens}")

    return response.text if response.text else "Вибач, не вдалося згенерувати текст новин."
